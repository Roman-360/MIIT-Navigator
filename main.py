class RouteDrawer(Widget):
    def __init__(self, **kwargs):
        super().__init__(**kwargs)
        self.relative_points = []
        self.bind(size=self.update_canvas, pos=self.update_canvas)

    def draw_path(self, relative_points):
        self.relative_points = relative_points
        self.update_canvas()

    def update_canvas(self, *args):
        self.canvas.clear()
        if not self.relative_points: return
        with self.canvas:
            Color(0.2, 0.5, 1, 1) # Синий цвет линии
            abs_points = []
            for rx, ry in self.relative_points:
                abs_points.extend([self.x + rx * self.width, self.y + ry * self.height])
            Line(points=abs_points, width=4, cap='round', joint='round')

